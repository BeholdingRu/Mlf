-- Проверяем, что КАЖДАЯ точка начала действительно существует
-- среди стихов вашей Синодальной Библии.
-- В идеале запрос возвращает 0 строк.
select
  p.portion_number,
  p.name_ru,
  p.book_order,
  p.start_chapter,
  p.start_verse
from public.torah_portions p
left join public.bible_verses v
  on v.book_order = p.book_order
 and v.chapter    = p.start_chapter
 and v.verse      = p.start_verse
where v.id is null
order by p.portion_number;


-- Проверяем точки окончания.
-- В идеале также 0 строк.
select
  p.portion_number,
  p.name_ru,
  p.book_order,
  p.end_chapter,
  p.end_verse
from public.torah_portions p
left join public.bible_verses v
  on v.book_order = p.book_order
 and v.chapter    = p.end_chapter
 and v.verse      = p.end_verse
where v.id is null
order by p.portion_number;


-- Пример: посмотреть все места начала паршийот прямо в тексте.
