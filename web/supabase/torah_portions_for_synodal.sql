  book_name,
  chapter,
  verse,
  start_portion_number,
  start_portion_name_ru,
  start_portion_name_he,
  start_portion_name_en
from public.bible_verses_with_torah_markers
where start_portion_id is not null
order by book_order, chapter, verse;


