-- ============================================================
-- 54 недельные главы Торы (паршийот) для существующей таблицы
-- public.bible_verses из add_synodal_bible.sql
--
-- Сопоставление с текстом делается НЕ по book_code, а по:
--   book_order + chapter + verse
--
-- Это позволяет не зависеть от того, как именно у вас названы
-- коды книг (GEN / Genesis / Быт и т.п.).
-- ============================================================

-- 1) Таблица границ недельных глав
create table if not exists public.torah_portions (
  id bigint generated by default as identity primary key,

  portion_number smallint not null unique
    check (portion_number between 1 and 54),

  name_en text not null,
  name_he text not null,
  name_ru text not null,

  -- 1=Бытие, 2=Исход, 3=Левит, 4=Числа, 5=Второзаконие
  book_order smallint not null
    check (book_order between 1 and 5),

  -- Не используется для JOIN; оставлено как читаемая метаинформация.
  book_code text not null,

  start_chapter smallint not null check (start_chapter > 0),
  start_verse   smallint not null check (start_verse > 0),
  end_chapter   smallint not null check (end_chapter > 0),
  end_verse     smallint not null check (end_verse > 0),

  created_at timestamptz not null default now(),

  unique (book_order, start_chapter, start_verse)
);

-- На случай, если ранее была создана версия torah_portions без book_order.
alter table public.torah_portions
  add column if not exists book_order smallint;

-- Если колонка добавилась в старую таблицу, наполним ее по стандартному book_code.
update public.torah_portions
set book_order = case book_code
  when 'Genesis' then 1
  when 'Exodus' then 2
  when 'Leviticus' then 3
  when 'Numbers' then 4
  when 'Deuteronomy' then 5
  else book_order
end
where book_order is null;

create index if not exists torah_portions_start_idx
  on public.torah_portions (book_order, start_chapter, start_verse);

create index if not exists torah_portions_end_idx
  on public.torah_portions (book_order, end_chapter, end_verse);


