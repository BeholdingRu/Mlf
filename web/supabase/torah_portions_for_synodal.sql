  on public.torah_portions
  for select
  to anon, authenticated
  using (true);


-- 4) Представление для фронтенда.
-- Для каждого стиха:
--   start_portion_* заполнено, если ПЕРЕД ним начинается новая парша;
--   end_portion_* заполнено, если ПОСЛЕ него заканчивается парша.
--
-- security_invoker=true заставляет view соблюдать RLS исходных таблиц.
drop view if exists public.bible_verses_with_torah_markers;

create view public.bible_verses_with_torah_markers
with (security_invoker = true)
as
select
  v.*,

  ps.id               as start_portion_id,
  ps.portion_number   as start_portion_number,
  ps.name_ru          as start_portion_name_ru,
  ps.name_en          as start_portion_name_en,
  ps.name_he          as start_portion_name_he,
  ps.start_chapter    as start_portion_chapter,
  ps.start_verse      as start_portion_verse,
  ps.end_chapter      as start_portion_end_chapter,
  ps.end_verse        as start_portion_end_verse,

  pe.id               as end_portion_id,
  pe.portion_number   as end_portion_number,
  pe.name_ru          as end_portion_name_ru,
  pe.name_en          as end_portion_name_en,
  pe.name_he          as end_portion_name_he

from public.bible_verses v

left join public.torah_portions ps
  on ps.book_order    = v.book_order
 and ps.start_chapter = v.chapter
 and ps.start_verse   = v.verse

left join public.torah_portions pe
  on pe.book_order  = v.book_order
 and pe.end_chapter = v.chapter
 and pe.end_verse   = v.verse;


